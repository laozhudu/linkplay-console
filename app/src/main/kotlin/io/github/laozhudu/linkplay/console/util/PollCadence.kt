package io.github.laozhudu.linkplay.console.util

/**
 * 所有轮询周期的**唯一来源**。
 *
 * ## 为什么要收在一处
 *
 * 收之前有 5 个周期散在 5 个文件里（500 / 1000 / 2500 / 3000 / 3000）。
 * 用户体感是「有时跟手有时不跟手」—— 但**逐个看都合理**，问题在没人能把它们放一起看。
 *
 * 收在这里之后，调手感只改这一个文件，也不用担心漏掉某一处。
 *
 * ## 为什么现在**不**把它们统一成同一个值
 *
 * 这五个用途不同，强行统一会伤害其中一些：
 *
 * | 用途 | 值 | 如果改成 1s 会怎样 |
 * |---|---:|---|
 * | 本机进度 | 500ms | 进度条一格一格跳，看着卡 |
 * | 首页卡片 | 3s | 每秒问每台设备，老固件被打爆（实测 `.153` 是 2018 年固件） |
 * | 组拓扑 | 3s | `slave_list` 请求量翻三倍，而组结构本来就很少变 |
 *
 * **所以这里收的是"定义"，不是"值"。** 值按各自的约束定，但必须写清理由 ——
 * 写不出理由的，说明该统一。
 */
object PollCadence {

    /**
     * 本机播放进度。
     *
     * Media3 **不会**在位置变化时回调，只在状态变化时给一次。不自己问，进度条就停着不动。
     * 500ms 是"看着连续"和"别白耗电"的折中（1s 会看出格）。
     */
    const val LOCAL_PROGRESS_MS = 500L

    /**
     * 播放页的设备状态（曲名/进度/音量）。
     *
     * 比首页快三倍，因为**播放页有进度条**，用户盯着看；首页只显示曲名。
     * 这条差异是刻意的，不是遗漏。
     */
    const val PLAYER_SCREEN_MS = 1_000L

    /**
     * 首页卡片心跳（每台设备的曲名/音量）。
     *
     * 3 秒而不是 1 秒：卡片信息变化慢，而且这是**逐台**请求 ——
     * 三台设备每秒各一次 `getPlayerStatus`，对 2018 年的固件来说太密。
     */
    const val CARD_HEARTBEAT_MS = 3_000L

    /**
     * 组拓扑（`slave_list`）。
     *
     * 只读几百字节，但组结构很少变；3 秒足够让"退组"在 3 秒内反映出来。
     * 从机在主机自开的 AP 网段里，手机连家里 WiFi **连不到**，所以只能靠这个轮询。
     */
    const val GROUP_TOPOLOGY_MS = 3_000L

    /**
     * 组主机音量。
     *
     * 多房间时原厂遥控器可能改了音量，这边要跟上。
     * 2.5 秒是因为它比曲名更"值钱"（用户最常调的就是音量），但又不必每秒。
     */
    const val GROUP_VOLUME_MS = 2_500L

    /** 定时关闭的时钟：秒级足够（界面显示的就是秒）。 */
    const val SLEEP_TICK_MS = 1_000L

    /** 配网 WPS 引导的轮询：一次性流程，两秒一次不着急。 */
    const val WPS_GUIDE_MS = 2_000L
}
